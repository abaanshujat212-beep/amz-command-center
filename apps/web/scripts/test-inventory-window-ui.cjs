const fs=require('node:fs'),assert=require('node:assert/strict'),Module=require('node:module'),path=require('node:path')
const root=path.resolve(__dirname,'..'),requireWeb=Module.createRequire(root+'/package.json')
const ts=requireWeb('typescript'),React=requireWeb('react'),{renderToStaticMarkup}=requireWeb('react-dom/server')
const filename=path.join(root,'components/inventory-velocity-evidence.tsx'),m=new Module(filename)
m.filename=filename;m.paths=Module._nodeModulePaths(root)
m._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText,filename)
const {velocityEvidence,InventoryVelocityEvidence}=m.exports
const now=Date.parse('2026-01-31T12:00:00Z')
function window(overrides={}) {return {windowDays:7,startDay:'2026-01-24',endDay:'2026-01-30',observedDays:7,missingDays:0,coverage:1,status:'complete',unitsObserved:0,averageDailyUnitsObserved:0,invalidRows:0,numericRangeExceeded:false,salesFreshness:'current',salesLoadedAt:'2026-01-31T09:00:00Z',latestSalesDate:'2026-01-30',...overrides}}
assert.equal(velocityEvidence(undefined,7,now),null)
assert.equal(velocityEvidence([],7,now),null)
assert.equal(velocityEvidence(window({windowDays:14}),7,now),null)
for(const fields of [{endDay:'2026-01-31'},{startDay:'2026-01-25'},{startDay:'2026-02-30'},{observedDays:6,missingDays:0},{observedDays:-1,missingDays:8},{observedDays:0,missingDays:7},{unitsObserved:NaN},{unitsObserved:Infinity},{unitsObserved:null},{averageDailyUnitsObserved:-1},{status:'fake'}]) assert.equal(velocityEvidence(window(fields),7,now),null)
assert.equal(velocityEvidence(window(),7,now).unitsObserved,0)
assert.equal(velocityEvidence(window(),7,now).averageDailyUnitsObserved,0)
assert.equal(velocityEvidence(window({status:'partial',observedDays:3,missingDays:4,unitsObserved:12,averageDailyUnitsObserved:4}),7,now).averageDailyUnitsObserved,4)
const invalid=velocityEvidence(window({invalidRows:1,unitsObserved:100,averageDailyUnitsObserved:100/7}),7,now)
assert.equal(invalid.status,'invalid');assert.equal(invalid.unitsObserved,null);assert.equal(invalid.averageDailyUnitsObserved,null)
const unsafe=velocityEvidence(window({numericRangeExceeded:true}),7,now)
assert.equal(unsafe.status,'invalid');assert.equal(unsafe.unitsObserved,null)
const noData=velocityEvidence(window({status:'no_data',observedDays:0,missingDays:7,unitsObserved:null,averageDailyUnitsObserved:null,latestSalesDate:null,salesLoadedAt:null}),7,now)
assert.equal(noData.salesFreshness,'unknown');assert.equal(noData.unitsObserved,null)
assert.equal(velocityEvidence(window({salesLoadedAt:'2026-02-01T00:00:00Z'}),7,now).salesFreshness,'unknown')
assert.equal(velocityEvidence(window({latestSalesDate:'2026-01-01'}),7,now).salesFreshness,'unknown')
function render(evidence,coverageBlocked=true){return renderToStaticMarkup(React.createElement(InventoryVelocityEvidence,{evidence,coverageBlocked}))}
const absent=render(undefined)
assert.equal((absent.match(/Evidence unavailable/g)||[]).length,3)
assert.doesNotMatch(absent,/Observed units|Average \/ observed day/)
const evidence={
 '7d':window(),
 '14d':window({windowDays:14,startDay:'2026-01-17',observedDays:3,missingDays:11,status:'partial',unitsObserved:12,averageDailyUnitsObserved:4,salesFreshness:'stale'}),
 '30d':window({windowDays:30,startDay:'2026-01-01',observedDays:30,missingDays:0,invalidRows:2,status:'invalid',unitsObserved:null,averageDailyUnitsObserved:null}),
}
const markup=render(evidence)
assert.match(markup,/2026-01-24 – 2026-01-30 UTC/)
assert.match(markup,/Observed units<\/dt><dd>0<\/dd>/)
assert.match(markup,/Average \/ observed day<\/dt><dd>0<\/dd>/)
assert.match(markup,/Partial history: this average covers observed days only/)
assert.match(markup,/Stale source: verify newer observations/)
assert.match(markup,/Observed \/ missing days<\/dt><dd>3 \/ 11<\/dd>/)
assert.match(markup,/Coverage remains unavailable until its warnings are resolved/)
assert.match(markup,/Invalid sales evidence/)
assert.match(markup,/Observed units<\/dt><dd>Unknown<\/dd>/)
assert.doesNotMatch(markup,/NaN|Infinity|Invalid Date/)
