const fs = require('node:fs')
const assert = require('node:assert/strict')
const Module = require('node:module')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const requireWeb = Module.createRequire(root + '/package.json')
const ts = requireWeb('typescript')
const React = requireWeb('react')
const { renderToStaticMarkup } = requireWeb('react-dom/server')
const loaded = new Map()
function load(relative) {
 const filename = path.join(root, relative)
 if(loaded.has(filename)) return loaded.get(filename).exports
 const m = new Module(filename)
 m.filename = filename
 m.paths = Module._nodeModulePaths(root)
 const native = m.require.bind(m)
 m.require = name => name.startsWith('@/') ? load(name.slice(2)+(fs.existsSync(path.join(root,name.slice(2)+'.ts'))?'.ts':'.tsx')) : name === 'next/link' ? {default: ({children, href, ...props}) => React.createElement('a', {href, ...props}, children)} : native(name)
 loaded.set(filename,m)
 m._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText,filename)
 return m.exports
}
const {inventoryFilters,inventoryPageHref} = load('lib/inventory-workspace.ts')
assert.equal(inventoryFilters({page:'1junk'}),null)
assert.equal(inventoryFilters({freshHours:'0'}),null)
assert.equal(inventoryFilters({sku:['a','b']}),null)
assert.equal(inventoryFilters({page:'9007199254740991'}),null)
assert.equal(inventoryFilters({freshHours:'8761'}),null)
assert.equal(inventoryFilters({location:'x'.repeat(101)}),null)
const filters=inventoryFilters({sku:' Test ',location:'wh&1',freshHours:'24'})
assert.deepEqual(filters,{sku:'Test',locationCode:'wh&1',page:1,pageSize:25,freshHours:24})
assert.match(inventoryPageHref(filters,2),/sku=Test/)
assert.match(inventoryPageHref(filters,2),/location=wh%261/)
assert.match(inventoryPageHref(filters,2),/page=2/)
